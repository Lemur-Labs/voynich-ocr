"""Static disagreement explorer over the published no-readings map outputs.

Reads the published per-column TSV and summary.json for one map (default: the full five-source
map, as regenerated by `make map` and byte-proven against results/map-v0 and the map-v0 release)
and emits a plain static site into build/explorer/: an index page, one page per manuscript folio,
and one page per glyph column.

Content boundary (VO-028, G1-7): the explorer renders only the published no-readings data —
class, tier, flag, contributing sources, gated. No readings, no codes, no transliteration text,
and no image files: folio and column pages link out to the Beinecke image and voynich.nu
instead. `check_boundary` verifies this mechanically after every build.
"""

import argparse
import html
import json
import re
import shutil
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

from voynich_ocr.snapshot import ROOT

BEINECKE_MANIFEST = "https://collections.library.yale.edu/manifests/2002046"
VOYNICH_NU_DATA = "https://www.voynich.nu/data/"
IMAGE_SUFFIXES = frozenset({".png", ".jpg", ".jpeg", ".gif", ".svg", ".webp", ".ico", ".avif"})

CLASS_LABELS = {
    "agree": "all contributing sources read the same",
    "disagree": "contributing sources differ",
    "granularity": "the coarse-alphabet sources cannot distinguish this reading",
    "unknown": "at least one contributing source wrote `?`",
    "unscorable": "fewer than two usable sources",
}

# rgb() everywhere: the boundary check greps the output for transliteration tokens like `a0`,
# and hex colors are full of letter-digit pairs. Body text is near-black on light grounds,
# which passes WCAG AA comfortably.
