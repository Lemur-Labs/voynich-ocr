@dataclass(frozen=True)
class Cell:
    """One glyph column, exactly what the published TSV row carries and nothing more."""

    locus: str
    index: int
    tier: int
    cls: str
    flag: str
    contributing: tuple[str, ...]
    gated: bool

    @property
    def page(self) -> str:
        return self.locus.rsplit(".", 1)[0]

    @property
    def slug(self) -> str:
        return f"{self.locus}-{self.index}"


PUBLISHED_HEADER = ["locus", "column", "tier", "class", "flag", "contributing", "gated"]


def read_cells(path: Path) -> list[Cell]:
    lines = path.read_text().splitlines()
    if lines[0].split("\t") != PUBLISHED_HEADER:
        sys.exit(f"explorer: unexpected published TSV header in {path}: {lines[0]}")
    cells = []
    for line in lines[1:]:
        locus, index, tier, cls, flag, contributing, gated = line.split("\t")
        cells.append(
            Cell(
                locus,
                int(index),
                int(tier),
                cls,
                flag,
                tuple(contributing.split(",")) if contributing else (),
                gated == "gated",
            )
        )
    return cells


def beinecke_images() -> dict[str, str]:
    """Per-folio IIIF image URLs, from the committed snapshot sources (links only, never embedded)."""
    sources = tomllib.loads((ROOT / "snapshot" / "sources.toml").read_text())["source"]
    return {Path(s["path"]).stem: s["url"] for s in sources if s["path"].startswith("images/")}


def folio_order(cells: list[Cell]) -> list[str]:
    """Folios in manuscript order, which is the TSV's order."""
    return list(dict.fromkeys(c.page for c in cells))


def cell_aria(c: Cell) -> str:
    bits = [
        f"column {c.index} of locus {c.locus}",
        c.cls,
        f"tier {c.tier}",
        f"sources {', '.join(c.contributing)}",
    ]
    if c.gated:
        bits.append("gated")
    if c.flag:
        bits.append(c.flag.replace("_", " "))
    return ", ".join(bits)


def strip(cells: list[Cell]) -> str:
    items = []
    for c in cells:
        classes = [f"c-{c.cls}", *(k for k in ("gated", c.flag) if k)]
        items.append(
            f'<li><a class="{" ".join(classes)}" href="../columns/{c.slug}.html" aria-label="{cell_aria(c)}"></a></li>'
        )
    return f'<ul class="strip">\n{"".join(items)}\n</ul>'


def legend() -> str:
    classes = "".join(
        f'<li><span class="sw c-{cls}" aria-hidden="true"></span><strong>{cls}</strong> — {CLASS_LABELS[cls]}</li>'
        for cls in sorted(CLASS_LABELS)
    )
    return f"""\
<ul class="legend">
{classes}
</ul>
<p><strong>Tier</strong> is how many of the five transliterations cover a column (1–5).
<strong>Gated</strong> columns are the ones the headline rate scores: tier ≥ 3, at least three
contributing sources, class agree or disagree, and not flagged ZL-uncertain. Hatched cells are
<code>zl_uncertain</code>: ZL's first-choice reading there is marked uncertain in the source.</p>
<p>These pages show where the published transliterations disagree — never what any of them read.
For the readings and the manuscript itself, follow the links to the Beinecke image and the
voynich.nu data files.</p>
"""


def page(title: str, h1: str, body: str, up: str = "../") -> str:
    return f"""\
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)}</title>
<style>{CSS}</style>
</head>
<body>
<header><a href="{up}index.html">voynich-ocr disagreement map — explorer</a></header>
<main>
<h1>{html.escape(h1)}</h1>
{body}
</main>
<footer>Data: voynich-ocr disagreement map v0 (CC BY 4.0). The explorer shows published map
classifications only — no readings, no codes, no images. Transliterations are © their authors;
manuscript images © Beinecke Rare Book &amp; Manuscript Library (public domain), linked, not embedded.</footer>
</body>
</html>
"""


def pct(n: int, d: int) -> str:
    return f"{n / d:.2%}" if d else "—"


def folio_stats(cells: list[Cell]) -> tuple[int, int, int]:
    gated = [c for c in cells if c.gated]
    return len(cells), sum(c.cls == "disagree" for c in gated), len(gated)


def external_links(folio: str, beinecke: dict[str, str]) -> str:
    image = beinecke.get(folio)
    label, href = (
        ("folio image at the Beinecke (IIIF)", image)
        if image
        else ("the manuscript at the Beinecke", BEINECKE_MANIFEST)
    )
    return f'<a href="{href}">{label}</a> · <a href="{VOYNICH_NU_DATA}">transliterations at voynich.nu</a>'


def write_index(out: Path, summary: dict, cells: list[Cell]) -> None:
    full = summary["maps"]["full"]["overall"]
    maps_rows = "".join(
        f"<tr><td>{name}</td><td>{', '.join(m['sources'])}</td><td>{m['overall']['columns']}</td>"
        f"<td>{m['overall']['gated']}</td><td>{m['overall']['gated_disagree']}</td>"
        f"<td>{m['overall']['gated_rate']}</td></tr>"
        for name, m in summary["maps"].items()
    )
    pair_rows = "".join(
        f"<tr><td>{pair}</td><td>{p['columns']}</td><td>{p['differ']}</td><td>{p['rate']}</td></tr>"
        for pair, p in summary["pairwise"].items()
    )
    folios = folio_order(cells)
    by_page: dict[str, list[Cell]] = {}
    for c in cells:
        by_page.setdefault(c.page, []).append(c)
    folio_rows = []
    for folio in folios:
        n, dis, gated = folio_stats(by_page[folio])
        folio_rows.append(
            f'<tr><td><a href="folios/{folio}.html">{folio}</a></td><td>{n}</td>'
            f"<td>{gated}</td><td>{dis}</td><td>{pct(dis, gated)}</td></tr>"
        )
    body = f"""\
<p>Where the five published transliterations of the Voynich manuscript (ZL, IT, GC, FG, CD) agree
and disagree on each of the {full['columns']:,} glyph columns of the shown pages, in the full map and
{len(summary['maps']) - 1} leave-one-out and reduced maps. {full['gated']:,} columns are gated into the headline
rate; {full['gated_disagree']:,} of them ({pct(full['gated_disagree'], full['gated'])}) are disagreements. The
{summary['withheld_test_pages']} test pages are withheld from everything published (VO-019) and have no pages here.</p>
{legend()}
<h2>Maps</h2>
<table><caption>Gated rates per map.</caption>
<tr><th scope="col">map</th><th scope="col">sources</th><th scope="col">columns</th><th scope="col">gated</th><th scope="col">gated disagree</th><th scope="col">gated rate</th></tr>
{maps_rows}</table>
<h2>Pairwise</h2>
<table><caption>Per pair of sources, over gated columns both contribute to.</caption>
<tr><th scope="col">pair</th><th scope="col">columns</th><th scope="col">differ</th><th scope="col">rate</th></tr>
{pair_rows}</table>
<h2>Folios</h2>
<table><caption>{len(folios)} folios. Disagree is gated disagreements; the rate is against gated columns.</caption>
<tr><th scope="col">folio</th><th scope="col">columns</th><th scope="col">gated</th><th scope="col">disagree</th><th scope="col">gated rate</th></tr>
{''.join(folio_rows)}</table>
"""
    out.joinpath("index.html").write_text(
        page("voynich-ocr disagreement map — explorer", "Disagreement map explorer", body, up="")
    )


def write_folio(out: Path, folio: str, folios: list[str], cells: list[Cell], beinecke: dict[str, str]) -> None:
    by_locus: dict[str, list[Cell]] = {}
    for c in cells:
        by_locus.setdefault(c.locus, []).append(c)
    at = folios.index(folio)
    prev = f'<a href="{folios[at - 1]}.html">← folio {folios[at - 1]}</a>' if at else ""
    nxt = f'<a href="{folios[at + 1]}.html">folio {folios[at + 1]} →</a>' if at + 1 < len(folios) else ""
    loci = "".join(
        f'<section class="locus"><h2>{locus}</h2>{strip(fcells)}</section>'
        for locus, fcells in by_locus.items()
    )
    n, dis, gated = folio_stats(cells)
    body = f"""\
<p class="bread"><a href="../index.html">↑ all folios</a> {prev} {nxt}</p>
<p>{external_links(folio, beinecke)}</p>
<p>{n:,} glyph columns on {len(by_locus)} loci; {gated:,} gated, {dis:,} gated disagreements
({pct(dis, gated)}). Each cell is one glyph column, colored by class; follow a cell for its detail.</p>
{legend()}
{loci}
"""
    out.joinpath(f"folios/{folio}.html").write_text(
        page(f"folio {folio} — disagreement map", f"Folio {folio}", body)
    )


def write_column(out: Path, c: Cell, beinecke: dict[str, str]) -> None:
    folio = c.page
    body = f"""\
<p class="bread"><a href="../index.html">↑ all folios</a> · <a href="../folios/{folio}.html">↑ folio {folio}</a></p>
<p>{external_links(folio, beinecke)}</p>
<dl>
<dt>locus</dt><dd>{c.locus}</dd>
<dt>column</dt><dd>{c.index}</dd>
<dt>class</dt><dd><span class="sw c-{c.cls}" aria-hidden="true"></span>{c.cls} — {CLASS_LABELS[c.cls]}</dd>
<dt>tier</dt><dd>{c.tier} of 5 sources</dd>
<dt>contributing sources</dt><dd>{', '.join(c.contributing)}</dd>
<dt>gated</dt><dd>{'yes' if c.gated else 'no'}</dd>
<dt>flag</dt><dd>{c.flag.replace('_', ' ') if c.flag else 'none'}</dd>
</dl>
<p>This page is the published map classification only. What each source reads here, and the
manuscript itself, live at the links above — they are not redistributed.</p>
"""
    out.joinpath(f"columns/{c.slug}.html").write_text(
        page(f"column {c.index} of {c.locus} — disagreement map", f"Glyph column {c.index} — locus {c.locus}", body)
    )


def token_atoms(summary: dict) -> frozenset[str]:
    """Every transliteration token the published summary names, split to atoms (`c0:t0` → `c0`, `t0`)."""
    atoms: set[str] = set()
    for pair in summary["pairwise"].values():
        for left, right, _ in pair["top"]:
            for token in (left, right):
                atoms.update(part for part in token.replace("~", ":").split(":") if part != "-")
    return frozenset(atoms)


def check_boundary(out: Path, summary: dict, loci: list[str]) -> list[str]:
    """The mechanical half of the VO-028 boundary: no transliteration tokens, no image files, no embedded
    images anywhere in the generated site. Links out are expected and allowed; images are not.

    Locus ids (the manuscript's own `f68v3.12` page addresses) are masked before the token scan:
    a folio like `f68v3` legitimately contains the token-shaped substring `v3`. A token outside a
    locus id is still a violation."""
    violations = []
    atoms = token_atoms(summary)
    # Atoms that never occur inside a locus or folio id can be matched directly; the rest are matched
    # only after the ids that contain them are removed.
    direct = sorted(a for a in atoms if not any(a in locus for locus in loci))
    folios = {locus.rsplit(".", 1)[0] for locus in loci}
    colliders = {
        a: re.compile("|".join(re.escape(i) for i in sorted({*loci, *folios}) if a in i))
        for a in atoms
        if a not in direct
    }
    for f in sorted(out.rglob("*")):
        if not f.is_file():
            continue
        if f.suffix.lower() in IMAGE_SUFFIXES:
            violations.append(f"{f.relative_to(out)}: image file")
            continue
        text = f.read_text()
        if "<img" in text or "url(" in text:
            violations.append(f"{f.relative_to(out)}: embedded image reference")
        hits = [
            atom
            for atom in direct
            if atom in text
        ]
        hits += [atom for atom, pattern in colliders.items() if atom in pattern.sub("", text)]
        violations += [f"{f.relative_to(out)}: transliteration token {atom!r}" for atom in hits]
    return violations


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="explorer")
    p.add_argument("--map-dir", type=Path, default=ROOT / "build" / "map")
    p.add_argument("--out", type=Path, default=ROOT / "build" / "explorer")
    p.add_argument("--map-name", default="full")
    args = p.parse_args(argv)

    summary = json.loads((args.map_dir / "summary.json").read_text())
    cells = read_cells(args.map_dir / "published" / f"{args.map_name}.tsv")
    beinecke = beinecke_images()

    if args.out.exists():
        shutil.rmtree(args.out)
    out = args.out
    out.joinpath("folios").mkdir(parents=True)
    out.joinpath("columns").mkdir()

    folios = folio_order(cells)
    write_index(out, summary, cells)
    by_page: dict[str, list[Cell]] = {}
    for c in cells:
        by_page.setdefault(c.page, []).append(c)
    for folio in folios:
        write_folio(out, folio, folios, by_page[folio], beinecke)
    for c in cells:
        write_column(out, c, beinecke)

    violations = check_boundary(out, summary, [c.locus for c in cells])
    if violations:
        for v in violations[:20]:
            print(f"boundary violation: {v}", file=sys.stderr)
        sys.exit(f"explorer: {len(violations)} boundary violations in {out}")

    print(f"explorer: wrote {1 + len(folios) + len(cells)} pages ({len(folios)} folios, {len(cells)} columns) to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
